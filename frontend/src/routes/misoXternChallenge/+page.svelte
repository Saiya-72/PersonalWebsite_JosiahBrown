<h2>Description</h2>
<p>Collaborated with a cross-university team in TechPoint's XTern Challenge, partnering with the Midcontinent Independent System Operator (MISO) to detect early signals of emerging energy policy strategy shifts. Leveraged Python, data visualization, and Generative AI tools—including large language models (LLMs) for social listening and sentiment analysis—to analyze public datasets, news coverage, and stakeholder communications across the Midwest energy grid. This work aimed to identify when utilities, developers, and lobbyists begin laying the groundwork for new policy directions, helping inform proactive decision-making in the energy sector.
