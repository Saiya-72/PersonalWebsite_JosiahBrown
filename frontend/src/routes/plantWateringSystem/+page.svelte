<h2>Description</h2>
<p>As requested by our client, Dr. Motato from the University of Indianapolis, my team and I engineered detailed designs for an automatic plant watering system that can water houseplants from a reservoir of water while the owner of the plants is not around to water them. It is easy to install, easy to use, and portable. As the project manager for this project, I monitored and managed the progress of the project as a whole, as well as ensured that deadlines were met and quality was guaranteed.
